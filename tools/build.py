#!/usr/bin/env python3
"""Build build/AARCADE.EXE and build/AARCADE.MAP with Borland C++ in DOSBox-X.

Requires Borland C++ under bin/BCPP31 (or ``--borland``) and the DOSBox-X
Flatpak ``com.dosbox_x.DOSBox-X``. The project root is mounted as C: and the
compiler as D:. Every src/*.c is compiled (and every src/*.asm assembled with
TASM). Undefined symbols get empty stubs in build/STUBS.C so the program still
links while matching is incomplete. Each C source is also compiled with ``-S``
into build/LST/; with the detailed segment map (``/s``) those listings give
necmp.py the size of every data item.

When build/res/ holds the scripts from extract_res.py, those resources are
compiled and bound. The pictures live in AACOLOR.DLL and AABW.DLL, which the
game loads from its own directory, so those two libraries are linked as well
from ``src/datalib/libmain.c`` plus Borland C0D/CWx (packed into one code
segment; AABW uses small-model C0DS+CWS, AACOLOR uses compact C0DC+CWC).
AACOLOR's trailing CodeView overlay is appended from
``build/res/AACOLOR/CODEVIEW.bin`` (written by extract_res.py) after bind.
The rebuilt EXE is for comparison only.

    .venv/bin/python tools/build.py
    .venv/bin/python tools/build.py --clean
    .venv/bin/python tools/build.py --borland bin/BCPP30
"""
from __future__ import annotations

import argparse
import re
import shutil
import struct
import subprocess
import sys
from pathlib import Path

from annotations import parse_tree

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "build"
ORIG = ROOT / "orig"
SRC = ROOT / "src"
DATALIB_SRC = SRC / "datalib" / "libmain.c"
DEFAULT_BORLAND = ROOT / "bin" / "BCPP31"
# Startup + runtime per picture DLL (confirmed against orig segment bytes):
# AABW is small-model C0DS (LockSegment in LibEntry); AACOLOR is compact C0DC
# (no LockSegment). Both link CWC — its HEAP routes malloc→farmalloc/GlobalAlloc
# and pulls ASMMEM/FHEAP with WEP just before ASMMEM, matching the originals.
DLL_STARTUP = {"AACOLOR": "C0DC", "AABW": "C0DS"}
DLL_RUNTIME = {"AACOLOR": "CWC", "AABW": "CWC"}
DLL_MODEL = {"AACOLOR": "-mc", "AABW": "-ms"}
# Set by main() before the build; run_dosbox mounts this as D:.
BORLAND = DEFAULT_BORLAND
# Optional second include tree (E:), used when the selected Borland lacks
# Windows 3.1 headers such as mmsystem.h. Searched after D:\\INCLUDE.
EXTRA_INCLUDE: Path | None = None
# Optional second Borland tree (F:) for --rc-tree, so commands can use F:\\BIN\\...
RC_TREE: Path | None = None

CFLAGS = ["-c", "-mm", "-2", "-p", "-WE", "-w-par"]
# Shared DLL compile flags; model (-ms/-mc) is per library in DLL_MODEL.
# -WD (not -WDE): DGROUP load in LibMain prolog, matching the originals.
# -zC_TEXT: put LibMain in _TEXT so packing merges it with C0D (not LIBMAIN_TEXT).
DLLFLAGS_COMMON = ["-c", "-2", "-p", "-WD", "-w-par", "-zC_TEXT"]
# /o: `offset` of a code label is a loader-resolved fixup, which TLINK keeps
# as an NE offset relocation the way the original has it (MmBind).
AFLAGS = ["/mx", "/m2", "/o"]
# DOS command prefixes: .RC / .RES / .EXE arguments are appended.
# Borland BRC writes the Windows 3.0 nametable form (WAVE as #32513) that
# the original uses; MS RC 3.10 stores custom types as strings instead.
RC_COMPILE = r"D:\BIN\BRC -30 -r"
RC_BIND = r"D:\BIN\BRC -30"
LIBS = ["IMPORT", "MATHWM", "CWM"]
DOSBOX = ["flatpak", "run", "com.dosbox_x.DOSBox-X"]
# Picture libraries the game loads by filename. METER.DLL is not one of them.
RES_LIBS = ("AACOLOR", "AABW")
PROTMODE = 0x0008

PLACEHOLDER_RE = re.compile(r"\bFUN_[0-9A-F]{4}_[0-9A-F]{4}\b")
UNDEFINED_RE = re.compile(r"Undefined symbol (\S+)")
EXPORT_RE = re.compile(r"^\s+(\w+)\s+@\d+", re.M)


def dos(path: Path) -> str:
    return "C:\\" + str(path.relative_to(ROOT)).replace("/", "\\").upper()


def defined_symbols() -> set[str]:
    names = set()
    # Only the EXE module: DLL FUNCTION annotations live under src/datalib/
    # and must not suppress EXE stubs or change the EXE link set.
    for a in parse_tree(SRC, "AARCADE"):
        if a.kind == "FUNCTION":
            names.add((a.symbol or a.name).upper())
    return names


def needed_stubs(extra: set[str]) -> list[str]:
    defined = defined_symbols()
    wanted = set(extra)
    for p in SRC.glob("*.[ch]"):
        wanted |= set(PLACEHOLDER_RE.findall(p.read_text(encoding="latin-1")))
    wanted |= set(EXPORT_RE.findall((SRC / "aarcade.def").read_text()))
    return sorted(s for s in wanted if s.lstrip("_").upper() not in defined)


def write_stubs(stubs: list[str]) -> None:
    lines = ["/* Generated by tools/build.py: placeholders for code not decompiled yet. */",
             "#include <windows.h>", ""]
    for s in stubs:
        if s.startswith("_"):
            lines.append(f"void cdecl {s[1:]}(void) {{}}")
        else:
            lines.append(f"void FAR PASCAL {s}(void) {{}}")
    (BUILD / "STUBS.C").write_text("\r\n".join(lines) + "\r\n")


def resources_ready() -> bool:
    res = BUILD / "res"
    return (res / "AARCADE.RC").exists() and all((res / f"{name}.RC").exists() for name in RES_LIBS)


def _libmain_obj(name: str) -> str:
    """Object basename for this DLL's LibMain (model-specific)."""
    return f"LIBMAIN_{DLL_STARTUP[name][-1]}"  # LIBMAIN_S / LIBMAIN_C


def write_datalib() -> None:
    """Module-definition and link response files for the picture DLLs."""
    if not DATALIB_SRC.exists():
        raise SystemExit(f"missing {DATALIB_SRC.relative_to(ROOT)}")
    for startup in set(DLL_STARTUP.values()):
        # Copy stock C0D; do not reorder EXTDEFs — FIXUPP entries index them.
        src = BORLAND / "LIB" / f"{startup}.OBJ"
        (BUILD / f"{startup}.OBJ").write_bytes(src.read_bytes())
    for name in RES_LIBS:
        (BUILD / f"{name}.DEF").write_text("\r\n".join([
            f"LIBRARY {name}",
            f"DESCRIPTION '{name}.DLL'",
            "EXETYPE WINDOWS",
            "PROTMODE",
            "CODE PRELOAD MOVEABLE DISCARDABLE",
            # SINGLEDATA matches the original NE flag bit; FIXED matches seg flags.
            "DATA PRELOAD FIXED SINGLE",
            "HEAPSIZE 4096",
            "EXPORTS",
            "    WEP @1 RESIDENTNAME",
            "",
        ]))
        startup = DLL_STARTUP[name]
        runtime = DLL_RUNTIME[name]
        libmain = _libmain_obj(name)
        # Packing on (no /P-). Model-matched CWx pulls near atexit / GlobalAlloc
        # farmalloc the way the originals were linked.
        (BUILD / f"{name}.RSP").write_text("\r\n".join([
            "/Twd /m /s /c /n +",
            f"{startup}.OBJ {libmain}.OBJ, +",
            f"{name}.DLL, +",
            f"{name}, +",
            f"D:\\LIB\\IMPORT D:\\LIB\\{runtime}.LIB, +",
            f"{name}.DEF",
            "",
        ]))


def _rc_tool(cmd: str) -> str:
    """Basename of the first token of a DOS command, uppercased (RC, BRC, …)."""
    first = cmd.split()[0].upper().replace("/", "\\")
    name = first.rsplit("\\", 1)[-1]
    return name[:-4] if name.endswith(".EXE") else name


def uses_ms_rc(cmd: str) -> bool:
    """Microsoft RC needs RCPP.EXE next to the .RC; Borland's BRC/BRCC do not."""
    return _rc_tool(cmd) == "RC"


def resource_lines() -> list[str]:
    """Compile and bind extracted resources. Empty when build/res/ is absent."""
    if not resources_ready():
        return []
    lines = ["ECHO binding resources >> BUILD.LOG", "CD \\BUILD\\RES"]
    if uses_ms_rc(RC_COMPILE):
        # RCPP lives next to RC; copy from the same drive the compile command uses.
        first = RC_COMPILE.split()[0].upper().replace("/", "\\")
        rcbin = first.rsplit("\\", 1)[0] if "\\" in first else "D:\\BIN"
        lines += [
            "IF EXIST RCPP.EXE DEL RCPP.EXE",
            "IF EXIST RCPP.ERR DEL RCPP.ERR",
            f"COPY {rcbin}\\RCPP.EXE",
            "IF ERRORLEVEL 1 GOTO RESFAIL",
            f"COPY {rcbin}\\RCPP.ERR",
            "IF ERRORLEVEL 1 GOTO RESFAIL",
        ]
    for name in ("AARCADE",) + RES_LIBS:
        lines += [f"{RC_COMPILE} {name}.RC >> C:\\BUILD\\BUILD.LOG",
                  "IF ERRORLEVEL 1 GOTO RESFAIL"]
    lines += [f"{RC_BIND} AARCADE.RES C:\\BUILD\\AARCADE.EXE >> C:\\BUILD\\BUILD.LOG",
              "IF ERRORLEVEL 1 GOTO RESFAIL",
              "CD \\BUILD"]
    # One LibMain object per memory model (small for AABW, compact for AACOLOR).
    compiled_models: set[str] = set()
    for name in RES_LIBS:
        model = DLL_MODEL[name]
        obj = _libmain_obj(name)
        if model in compiled_models:
            continue
        compiled_models.add(model)
        flags = " ".join(DLLFLAGS_COMMON + [model, f"-o{obj}.OBJ"])
        lines += [f"BCC {flags} {dos(DATALIB_SRC)} >> BUILD.LOG",
                  "IF ERRORLEVEL 1 GOTO RESFAIL"]
    for name in RES_LIBS:
        lines += [
            f"TLINK @{name}.RSP >> BUILD.LOG",
            "IF ERRORLEVEL 1 GOTO RESFAIL",
            "CD \\BUILD\\RES",
            f"{RC_BIND} {name}.RES C:\\BUILD\\{name}.DLL >> C:\\BUILD\\BUILD.LOG",
            "IF ERRORLEVEL 1 GOTO RESFAIL",
            "CD \\BUILD",
        ]
    if uses_ms_rc(RC_COMPILE):
        lines += ["CD \\BUILD\\RES",
                  "DEL RCPP.EXE",
                  "DEL RCPP.ERR",
                  "CD \\BUILD"]
    return lines


def write_scripts(sources: list[Path]) -> None:
    includes = "D:\\INCLUDE"
    if EXTRA_INCLUDE is not None:
        includes += ";E:\\"
    includes += ";C:\\SRC"
    (BUILD / "TURBOC.CFG").write_text(f"-I{includes}\r\n-LD:\\LIB\r\n")
    (BUILD / "TLINK.CFG").write_text("-LD:\\LIB\r\n")
    deflines = (SRC / "aarcade.def").read_text().splitlines()
    (BUILD / "AARCADE.DEF").write_text("\r\n".join(deflines) + "\r\n")
    objs = [p.stem.upper() for p in sources]
    rsp = [
        "/Twe /m /s /c /n /P- +",
        "D:\\LIB\\C0WM " + " ".join(objs) + ", +",
        "AARCADE, +",
        "AARCADE, +",
        " ".join(f"D:\\LIB\\{lib}" for lib in LIBS) + ", +",
        "AARCADE.DEF",
    ]
    (BUILD / "LINK.RSP").write_text("\r\n".join(rsp) + "\r\n")
    bat = ["@ECHO OFF", "C:", "CD \\BUILD", "PATH D:\\BIN",
           "IF EXIST AARCADE.EXE DEL AARCADE.EXE",
           "IF EXIST AARCADE.MAP DEL AARCADE.MAP",
           "IF NOT EXIST LST\\NUL MD LST",
           "ECHO building > BUILD.LOG"]
    for p in sources:
        if p.suffix.lower() == ".asm":
            bat.append(f"TASM {' '.join(AFLAGS)} {dos(p)},{p.stem.upper()}.OBJ >> BUILD.LOG")
        else:
            bat.append(f"BCC {' '.join(CFLAGS)} {dos(p)} >> BUILD.LOG")
            bat.append("IF ERRORLEVEL 1 GOTO FAIL")
            bat.append(f"BCC -S -nLST {' '.join(CFLAGS[1:])} {dos(p)} > NUL")
        bat.append("IF ERRORLEVEL 1 GOTO FAIL")
    if resources_ready():
        write_datalib()
    bat += ["TLINK @LINK.RSP >> BUILD.LOG", "IF ERRORLEVEL 1 GOTO FAIL"]
    bat += resource_lines()
    bat += ["ECHO OK > STATUS.TXT", "GOTO END",
            ":FAIL", "ECHO FAIL > STATUS.TXT", "GOTO END"]
    if resources_ready():
        bat += [":RESFAIL", "CD \\BUILD\\RES"]
        if uses_ms_rc(RC_COMPILE):
            bat += ["IF EXIST RCPP.EXE DEL RCPP.EXE",
                    "IF EXIST RCPP.ERR DEL RCPP.ERR"]
        bat += ["CD \\BUILD", "ECHO FAIL > STATUS.TXT"]
    bat += [":END"]
    (BUILD / "BUILD.BAT").write_text("\r\n".join(bat) + "\r\n")


def run_dosbox(timeout: int) -> str:
    status = BUILD / "STATUS.TXT"
    status.unlink(missing_ok=True)
    cmd = DOSBOX + [
        "-defaultconf", "-fastlaunch", "-silent", "-time-limit", str(timeout),
        "-set", "cpu cycles=max",
        "-set", "dosbox memsize=16",
        "-c", f'MOUNT C "{ROOT}"',
        "-c", f'MOUNT D "{BORLAND}"',
    ]
    if EXTRA_INCLUDE is not None:
        cmd += ["-c", f'MOUNT E "{EXTRA_INCLUDE}"']
    if RC_TREE is not None:
        cmd += ["-c", f'MOUNT F "{RC_TREE}"']
    cmd += ["-c", "C:\\BUILD\\BUILD.BAT", "-c", "EXIT"]
    subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=timeout + 30)
    return status.read_text().strip() if status.exists() else "TIMEOUT"


def link_sources() -> list[Path]:
    """Object order is the original NE code-segment order.

    That is the link order, and Borland concatenates each module's initialized
    data (string literals at the end of the module) in that order. mmstub.asm
    shares `_TEXT` with the startup code, so its functions live in segment 1,
    but its data begins at 0024:02C4, immediately after view.c. globals.c still
    holds data whose module is not decided; it stays after the segment-ordered
    objects so it does not shift the prefix that already matches.
    """
    seg: dict[Path, int] = {}
    # AARCADE only: FUNCTION annotations on src/datalib/libmain.c are for the
    # picture DLLs and must not pull that file into the EXE link.
    for a in parse_tree(SRC, "AARCADE"):
        if a.kind != "FUNCTION" or a.file.name.lower() == "mmstub.asm":
            continue
        seg[a.file] = min(a.seg, seg.get(a.file, a.seg))
    ordered = [path for path, _ in sorted(seg.items(), key=lambda kv: (kv[1], kv[0].name))]
    view = next(path for path in ordered if path.name.lower() == "view.c")
    ordered.insert(ordered.index(view) + 1, SRC / "mmstub.asm")
    for path in sorted(SRC.glob("*.c")):
        if path not in ordered:
            ordered.append(path)
    return ordered + [BUILD / "STUBS.C"]


def has_protmode(path: Path) -> bool:
    data = path.read_bytes()
    ne = int.from_bytes(data[0x3C:0x40], "little")
    if data[ne:ne + 2] != b"NE":
        raise ValueError(f"{path.name} is not an NE executable")
    flags = int.from_bytes(data[ne + 0x0C:ne + 0x0E], "little")
    return bool(flags & PROTMODE)


def keep_protmode(path: Path) -> None:
    """Set the NE protected-mode bit. Some binders clear it."""
    data = bytearray(path.read_bytes())
    ne = int.from_bytes(data[0x3C:0x40], "little")
    if data[ne:ne + 2] != b"NE":
        raise ValueError(f"{path.name} is not an NE executable")
    flags = int.from_bytes(data[ne + 0x0C:ne + 0x0E], "little") | PROTMODE
    data[ne + 0x0C:ne + 0x0E] = flags.to_bytes(2, "little")
    path.write_bytes(data)


def _last_resource_end(data: bytes) -> int:
    """File offset just past the last resource payload (alignment included)."""
    ne = int.from_bytes(data[0x3C:0x40], "little")
    res_table = ne + int.from_bytes(data[ne + 0x24:ne + 0x26], "little")
    shift = int.from_bytes(data[res_table:res_table + 2], "little")
    p = res_table + 2
    last = 0
    while True:
        rtype = int.from_bytes(data[p:p + 2], "little")
        if rtype == 0:
            break
        count = int.from_bytes(data[p + 2:p + 4], "little")
        p += 8
        for _ in range(count):
            off, length = struct.unpack_from("<HH", data, p)[:2]
            p += 12
            end = (off << shift) + (length << shift)
            if end > last:
                last = end
    return last


def append_debug_overlay(name: str) -> str | None:
    """Append a CodeView (NB02) trailer saved by extract_res.py.

    AACOLOR ships with one; AABW does not. Rebuilding with ``-v`` will not
    reproduce those bytes, so extract_res.py writes
    ``build/res/<name>/CODEVIEW.bin`` and we glue it on after bind.
    """
    overlay_path = BUILD / "res" / name / "CODEVIEW.bin"
    rebuilt = BUILD / f"{name}.DLL"
    if not overlay_path.exists() or not rebuilt.exists():
        return None
    overlay = overlay_path.read_bytes()
    if len(overlay) < 8 or overlay[-8:-4] != b"NB02":
        return None
    data = rebuilt.read_bytes()
    if data.endswith(overlay):
        return f"{name}.DLL: CodeView overlay already present"
    # Drop a partial/wrong trailer if a previous bind left one, then append.
    end = _last_resource_end(data)
    rebuilt.write_bytes(data[:end] + overlay)
    return (f"{name}.DLL: appended {len(overlay)}-byte CodeView overlay "
            f"from {overlay_path.relative_to(ROOT)}")


def build(timeout: int) -> tuple[str, str]:
    sources = link_sources()
    write_scripts(sources)
    status = run_dosbox(timeout)
    notes = []
    if status == "OK" and resources_ready():
        for name in ("AARCADE.EXE",) + tuple(f"{lib}.DLL" for lib in RES_LIBS):
            path = BUILD / name
            if has_protmode(path):
                notes.append(f"{name}: PROTMODE already set after bind")
            else:
                keep_protmode(path)
                notes.append(f"{name}: PROTMODE was clear after bind; patched")
        for lib in RES_LIBS:
            note = append_debug_overlay(lib)
            if note:
                notes.append(note)
    log = (BUILD / "BUILD.LOG").read_text(encoding="latin-1") if (BUILD / "BUILD.LOG").exists() else ""
    if notes:
        extra = "\n".join(notes) + "\n"
        (BUILD / "BUILD.LOG").write_text(log + extra, encoding="latin-1")
        log += extra
    return status, log


def resolve_borland(path: Path) -> Path:
    """Absolute path to a Borland tree that has BIN/BCC.EXE."""
    cand = path if path.is_absolute() else ROOT / path
    if not (cand / "BIN" / "BCC.EXE").exists():
        raise SystemExit(f"Borland C++ not found at {cand}")
    return cand.resolve()


def main() -> int:
    global BORLAND, EXTRA_INCLUDE, RC_TREE, RC_COMPILE, RC_BIND
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument("--timeout", type=int, default=120, help="seconds before DOSBox-X is killed")
    ap.add_argument("--clean", action="store_true",
                    help="delete build/ first, except extracted resources")
    ap.add_argument("--borland", type=Path, default=DEFAULT_BORLAND,
                    help="Borland C++ tree to mount as D: (default: bin/BCPP31)")
    ap.add_argument("--rc-tree", type=Path,
                    help="second Borland tree mounted as F: (use F:\\BIN\\... in --rc-*)")
    ap.add_argument("--rc-compile", default=RC_COMPILE,
                    help=r"DOS command prefix to compile .RC to .RES (default: D:\BIN\BRC -30 -r)")
    ap.add_argument("--rc-bind", default=RC_BIND,
                    help=r"DOS command prefix to bind .RES into an EXE/DLL (default: D:\BIN\BRC -30)")
    args = ap.parse_args()
    BORLAND = resolve_borland(args.borland)
    RC_COMPILE = args.rc_compile
    RC_BIND = args.rc_bind
    EXTRA_INCLUDE = None
    RC_TREE = None
    if args.rc_tree:
        RC_TREE = resolve_borland(args.rc_tree)
        print(f"note: mounting {RC_TREE} as F:", file=sys.stderr)
    if not (BORLAND / "INCLUDE" / "MMSYSTEM.H").exists():
        fallback = DEFAULT_BORLAND / "INCLUDE"
        if (fallback / "MMSYSTEM.H").exists() and fallback.resolve() != (BORLAND / "INCLUDE").resolve():
            EXTRA_INCLUDE = fallback.resolve()
            print(f"note: mounting {EXTRA_INCLUDE} as E: for mmsystem.h", file=sys.stderr)
    if args.clean and BUILD.exists():
        for child in BUILD.iterdir():
            if child.name.lower() == "res":
                continue
            if child.is_dir():
                shutil.rmtree(child)
            else:
                child.unlink()
    BUILD.mkdir(exist_ok=True)

    extra: set[str] = set()
    for _ in range(3):
        write_stubs(needed_stubs(extra))
        status, log = build(args.timeout)
        missing = set(UNDEFINED_RE.findall(log)) - extra
        if status == "OK" or not missing:
            break
        extra |= missing

    print(log.strip())
    print(f"\nbuild: {status}")
    return 0 if status == "OK" else 1


if __name__ == "__main__":
    sys.exit(main())
